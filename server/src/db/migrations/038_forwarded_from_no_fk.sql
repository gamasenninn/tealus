-- 他の部屋へ転送された投稿がある部屋を削除できなかった (改善ループ 2026-10-13 の 2.)
--
-- ★ 原因: forwarded_from が messages(id) を参照し、ON DELETE が無かった (019)。部屋を消すと messages は
--   CASCADE で消えるが、**別の部屋にある転送の写し**の参照に当たって削除全体が失敗し、500 だけが返った
--   (本番: 別の部屋への転送 69 件、転送元の部屋 14。うちグループ 12 室は削除できない状態だった)。
-- ★ 参照の縛りだけ外す。ID は残す:
--   - 写しは残る。画面は既にある「📤 転送メッセージ（元メッセージは削除されました）」を出す
--   - SET NULL にすると「転送」の印ごと消える (画面は forwarded_from が空なら転送の見出しを出さない)
--   - 存在しない投稿を転送元にした投稿は、アプリ側 (services/messageRefs.mts) が今までどおり断る
-- ★ reply_to は外さない: 返信は同じ部屋に限るので、部屋の削除では元と一緒に消える
ALTER TABLE messages DROP CONSTRAINT IF EXISTS messages_forwarded_from_fkey;
