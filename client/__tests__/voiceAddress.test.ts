import { describe, it, expect } from 'vitest';
import { applyAddress } from '../src/utils/voiceAddress';

// 宛名の候補を 1 タップで当てる。冒頭に呼びかけがあれば差し替え、無ければ先頭に足す
describe('applyAddress', () => {
  it.each([
    ['佐藤さん、取れます？ はい。', '斎藤さん', '斎藤さん、取れます？ はい。'],
    ['コマさん、取れますか？', 'ガマさん', 'ガマさん、取れますか？'],
    ['八木沢先生、さっきのマルチャー', '斎藤さん', '斎藤さん、八木沢先生、さっきのマルチャー'],   // 「先生」は印でないので足す
    ['斎藤君とれますか。', '高山君', '高山君とれますか。'],
    ['休憩戻りました。はい。', 'ガマ', 'ガマ、休憩戻りました。はい。'],
    ['はい。ドライバーさんが会社の方に連絡', '中さん', '中さん、はい。ドライバーさんが会社の方に連絡'],
    ['', '保坂さん', '保坂さん、'],
    ['お客様、到着しました', '中さん', '中さん、お客様、到着しました'],   // ★「様」は印にしない
  ])('%s + %s → %s', (text, cand, expected) => {
    expect(applyAddress(text, cand)).toBe(expected);
  });

  it('同じ宛名をもう一度押しても変わらない', () => {
    expect(applyAddress('ガマさん、OK', 'ガマさん')).toBe('ガマさん、OK');
  });

  it('先頭の空白は落としてから当てる', () => {
    expect(applyAddress('  佐藤さん、OK', '斎藤さん')).toBe('斎藤さん、OK');
  });
});
